#!/usr/bin/env python3
"""Regenerate the v3.3.0 map translations from the pinned upstream revisions.

Usage: python3 tools/generate_v11_maps.py /path/to/polishedcrystal
No checkout or network access is needed; both commits must exist locally.
"""

import re
import subprocess
import sys
from pathlib import Path

OLD_REV = "3fa43192379df5c3e7b09a08e4d5d79af4f02f42"  # v3.2.3
NEW_REV = "84acd5a45e32b368755254cee44e6df8344ddfaf"  # audited master, SAVE_VERSION 11

# Renames, merges, and splits. Current-position conversion is deliberately
# restricted to POKECENTER_2F; these mappings cover persistent map references.
RENAMES = {
    "WAREHOUSE_ENTRANCE": "GOLDENROD_UNDERGROUND",
    "UNDERGROUND_PATH_SWITCH_ROOM_ENTRANCES": "GOLDENROD_UNDERGROUND_SWITCH_ROOM",
    "UNDERGROUND_WAREHOUSE": "GOLDENROD_UNDERGROUND_WAREHOUSE",
    "UNDERGROUND": "UNDERGROUND_PATH",
    "ROUTE_6_UNDERGROUND_ENTRANCE": "ROUTE_6_UNDERGROUND_PATH_ENTRANCE",
    "ROUTE_5_UNDERGROUND_ENTRANCE": "ROUTE_5_UNDERGROUND_PATH_ENTRANCE",
    "ROUTE_23": "ROUTE_23_NORTH",
    "ROUTE_13_EAST": "ROUTE_13",
    "ROUTE_13_WEST": "ROUTE_13",
    "FARAWAY_ISLAND": "FARAWAY_ISLAND_SOUTH",
    "ROUTE_16_NORTHEAST": "ROUTE_16_EAST",
    "ROUTE_16_SOUTH": "ROUTE_16_EAST",
    "ROUTE_16_NORTHWEST": "ROUTE_16_NORTH",
    "ROUTE_17": "ROUTE_17_SOUTH",
    "CELADON_DEPT_STORE_6F": "CELADON_DEPT_STORE_ROOF",
}


def read(repo, rev, path):
    return subprocess.check_output(
        ["git", "-C", str(repo), "show", f"{rev}:{path}"], text=True
    )


def maps(source):
    group = number = 0
    result = {}
    for line in source.splitlines():
        if re.match(r"\s+newgroup\b", line):
            group += 1
            number = 0
        match = re.match(r"\s+map_const\s+(\w+),", line)
        if match:
            number += 1
            result[match[1]] = (group, number)
    return result


def generate(repo):
    old = maps(read(repo, OLD_REV, "constants/map_constants.asm"))
    new = maps(read(repo, NEW_REV, "constants/map_constants.asm"))
    lines = [
        "// Generated by tools/generate_v11_maps.py; do not edit by hand.",
        f"// v3.2.3: {OLD_REV}", f"// master: {NEW_REV}",
        "#pragma once", "#include <cstdint>", "",
        "namespace patchVersion10to11Namespace {", "",
        "struct MapChange { uint8_t oldGroup, oldNumber, newGroup, newNumber; };",
        "constexpr MapChange mapChanges[] = {",
    ]
    for name, before in old.items():
        target = RENAMES.get(name, name)
        after = new[target]  # Fail on an unreviewed deletion/rename.
        if before != after:
            values = ", ".join(map(str, before + after))
            label = name if name == target else f"{name} -> {target}"
            lines.append(f"\t{{{values}}}, // {label}")
    lines += ["};", "", "struct CenterWarp { uint8_t group, number, warp, outsideGroup, outsideNumber, outsideWarp; };",
              "constexpr CenterWarp centerWarps[] = {"]
    # Map names in data/maps/maps.asm correspond positionally to map_constants.
    names = re.findall(r"^\s+map\s+(\w+),", read(repo, NEW_REV, "data/maps/maps.asm"), re.M)
    assert len(names) == len(new)
    for name, (_, pair) in zip(names, new.items()):
        if "Poke" not in name:
            continue
        source = read(repo, NEW_REV, f"maps/{name}.asm")
        warps = re.findall(r"^\s+warp_event\s+[^,]+,\s*[^,]+,\s*(\w+),\s*(-?\d+)", source, re.M)
        for index, (dest, _) in enumerate(warps, 1):
            if dest == "POKECENTER_2F" and name != "PokeCenter2F":
                outside = new[warps[0][0]]
                lines.append(f"\t{{{pair[0]}, {pair[1]}, {index}, {outside[0]}, {outside[1]}, {warps[0][1]}}}, // {name}")
        if name == "SnowtopPokeCenter1F":
            # The upstairs was removed; return to the entrance of the same center.
            assert all(dest != "POKECENTER_2F" for dest, _ in warps)
            outside = new[warps[0][0]]
            lines.append(f"\t{{{pair[0]}, {pair[1]}, 1, {outside[0]}, {outside[1]}, {warps[0][1]}}}, // {name}: stairs removed; use entrance")
    lines += ["};", "", "} // namespace patchVersion10to11Namespace", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    output = Path(__file__).resolve().parents[1] / "include/patching/Version11Maps.h"
    output.write_text(generate(Path(sys.argv[1])), encoding="utf-8", newline="\n")
    print(f"Wrote {output}")
